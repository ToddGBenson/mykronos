from mykronos.auth import TokenRegistry
from mykronos.config import get_settings
from mykronos.db import Database
from mykronos.db.models import Organization, RepoOnboarding, WorkflowInstallEvent
from mykronos.github import FakeGitHubClient
from mykronos.installer import (
    BRANCH_PREFIX,
    DEFAULT_SECRET_NAME,
    GENERATED_MARKER,
    InstallerError,
    PathCollisionError,
    TemplateLibrary,
    WorkflowInstaller,
)

REPO = "example-org/payments-api"
SAST_PATH = ".github/workflows/mykronos-sast.yml"
SECRETS_PATH = ".github/workflows/mykronos-secrets.yml"

GENERIC_TEMPLATE = (
    "# Generated by Mykronos Workflow Installer - template version: "
    "<< template_version >>\n"
    "name: Mykronos << capability >>\n"
    "on: [pull_request]\n"
    "jobs:\n"
    "  scan:\n"
    "    runs-on: ubuntu-latest\n"
    "    steps:\n"
    "      - uses: << upload_action_ref >>\n"
    "        with:\n"
    "          token: ${{ secrets.<< token_secret_name >> }}\n"
)


