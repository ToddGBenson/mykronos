"""Workflow Installer — spec 03.

The interesting behaviour is all in the edges: what happens on a repeated
save, on a half-finished PR, and when a human already owns the path we want.

Two libraries are in play. `installer` uses the real shipped templates, for
assertions about the actual rendered SAST workflow. `multi` uses a synthetic
two-capability library, because the installer's diffing and idempotency logic
is inherently multi-capability while Phase 1 ships exactly one template —
testing that against a fixture means these tests keep asserting the same thing
when Phase 2 adds five more.
"""

