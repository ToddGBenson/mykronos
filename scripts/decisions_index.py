"""The decision index: `docs/DECISIONS.md` lists `docs/decisions/` (D-149).

From D-137 on, a decision is one file, `docs/decisions/D-nnn-<slug>.md`, in the
entry format the log always used: a `## D-nnn — Title` heading, a status line,
then the decision and why. `docs/DECISIONS.md` keeps D-001 to D-136 as they
were written, and carries a generated list of the files between two markers.
This script writes that list, and `--check` says whether it is current; the
test suite runs the check, so a decision file nobody indexed fails CI.

During the transition, D-137 onward may still sit in `docs/DECISIONS.md`
itself: PRs opened before this change append there. Those entries are not
listed here, because they are readable where they are, and a list that named
them would go stale the moment one of those PRs merged.
`scripts/move-decisions-to-files.py` moves them into files once those PRs are
in, and regenerates this list.

Usage: python scripts/decisions_index.py [--check] [--root PATH]
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOG = Path("docs") / "DECISIONS.md"
DIRECTORY = Path("docs") / "decisions"

START = "<!-- decisions-index:start (generated by scripts/decisions_index.py; do not edit) -->"
END = "<!-- decisions-index:end -->"

FILENAME = re.compile(r"^D-(\d{3,})-([a-z0-9]+(?:-[a-z0-9]+)*)\.md$")
HEADING = re.compile(r"^## (D-\d+) — (.*)$", re.MULTILINE)


@dataclass(frozen=True)
class DecisionFile:
    number: str  # "D-149"
    title: str
    path: Path  # relative to the repository root


def decision_files(root: Path = ROOT) -> tuple[list[DecisionFile], list[str]]:
    """Every decision file, by number, and every problem reading them."""
    directory = root / DIRECTORY
    found: list[DecisionFile] = []
    problems: list[str] = []
    if not directory.is_dir():
        return found, problems
    for path in sorted(directory.glob("*.md")):
        if path.name == "README.md":
            continue
        match = FILENAME.match(path.name)
        if not match:
            problems.append(
                f"{path.name}: a decision file is named D-nnn-<lowercase-slug>.md"
            )
            continue
        headings = HEADING.findall(path.read_text(encoding="utf-8"))
        if len(headings) != 1:
            problems.append(
                f"{path.name}: a decision file holds exactly one '## D-nnn — Title' "
                f"heading; it has {len(headings)}"
            )
            continue
        number, title = headings[0]
        if number != f"D-{match.group(1)}":
            problems.append(
                f"{path.name}: the heading says {number}, the filename D-{match.group(1)}"
            )
            continue
        found.append(DecisionFile(number, title.strip(), path.relative_to(root)))
    found.sort(key=lambda d: int(d.number[2:]))
    return found, problems


def render(files: list[DecisionFile]) -> str:
    """The block between the markers, markers included."""
    lines = [START, ""]
    if files:
        for d in files:
            link = d.path.relative_to(Path("docs")).as_posix()
            lines.append(f"- [{d.number} — {d.title}]({link})")
    else:
        lines.append("_No decision files yet._")
    lines += ["", END]
    return "\n".join(lines)


def _span(text: str) -> tuple[int, int] | None:
    start = text.find(START)
    end = text.find(END)
    if start < 0 or end < start:
        return None
    return start, end + len(END)


def check(root: Path = ROOT) -> list[str]:
    """Why the index is not current, or an empty list."""
    files, problems = decision_files(root)
    text = (root / LOG).read_text(encoding="utf-8")
    span = _span(text)
    if span is None:
        return [*problems, f"{LOG.as_posix()} has no index markers"]
    current = text[span[0] : span[1]].replace("\r\n", "\n")
    if current != render(files):
        problems.append(
            f"the index in {LOG.as_posix()} does not match {DIRECTORY.as_posix()}/: "
            "run `python scripts/decisions_index.py`"
        )
    return problems


def write(root: Path = ROOT) -> bool:
    """Regenerate the index in place. True when the file changed."""
    files, problems = decision_files(root)
    if problems:
        raise SystemExit("\n".join(problems))
    path = root / LOG
    raw = path.read_bytes().decode("utf-8")
    span = _span(raw)
    if span is None:
        raise SystemExit(f"{LOG.as_posix()} has no index markers")
    block = render(files)
    if "\r\n" in raw[span[0] : span[1]]:
        block = block.replace("\n", "\r\n")
    updated = raw[: span[0]] + block + raw[span[1] :]
    if updated == raw:
        return False
    path.write_bytes(updated.encode("utf-8"))
    return True


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check", action="store_true", help="fail if the index is stale"
    )
    parser.add_argument("--root", type=Path, default=ROOT)
    args = parser.parse_args(argv)
    if args.check:
        problems = check(args.root)
        for p in problems:
            print(p, file=sys.stderr)
        return 1 if problems else 0
    changed = write(args.root)
    print("index updated" if changed else "index already current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
